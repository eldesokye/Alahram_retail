from __future__ import annotations

import logging
import re

import requests
from markupsafe import Markup, escape

_logger = logging.getLogger(__name__)

PDF_REPORT = 'aypatech_ai_agent.reports_action_report_pdf'
INK, MUTED, LINE, PRIMARY = '#13262a', '#5b6b6d', '#e3e8e8', '#1f6f78'
TELEGRAM_BASE_URL = 'https://api.telegram.org'
TELEGRAM_MESSAGE_LIMIT = 4096


def markdown_to_html(text: str) -> Markup:
    """Render a modest Markdown subset (headers, bold, italics, lists, code) to safe HTML.

    The agent's answer is plain Markdown, not raw HTML, and there is no
    bundled Markdown engine for server-side rendering (the chat UI's own
    renderer is JavaScript). This covers what an agent summary typically
    uses without pulling in a new Python dependency, and escapes everything
    else so nothing the model writes can inject markup.
    """
    text = text or ''
    lines = text.replace('\r\n', '\n').split('\n')
    html_parts = []
    in_list = False
    in_code = False
    paragraph: list[str] = []

    def flush_paragraph():
        if paragraph:
            html_parts.append(
                Markup('<p style="margin:6px 0;font-size:13px;line-height:1.5;color:%s">%s</p>')
                % (INK, Markup(' ').join(paragraph))
            )
            paragraph.clear()

    def inline(line: str) -> Markup:
        safe = str(escape(line))
        safe = re.sub(r'\*\*(.+?)\*\*', r'<strong>\1</strong>', safe)
        safe = re.sub(r'(?<!\*)\*(.+?)\*(?!\*)', r'<em>\1</em>', safe)
        safe = re.sub(r'`(.+?)`', r'<code style="background:#f1f3f3;padding:1px 4px;border-radius:4px">\1</code>', safe)
        return Markup(safe)

    for raw_line in lines:
        line = raw_line.rstrip()
        if line.strip().startswith('```'):
            in_code = not in_code
            continue
        if in_code:
            html_parts.append(Markup('<pre style="background:#f1f3f3;padding:8px;border-radius:6px;font-size:12px;white-space:pre-wrap">%s</pre>') % escape(line))
            continue
        stripped = line.strip()
        if not stripped:
            flush_paragraph()
            if in_list:
                html_parts.append(Markup('</ul>'))
                in_list = False
            continue
        header_match = re.match(r'^(#{1,4})\s+(.*)$', stripped)
        if header_match:
            flush_paragraph()
            if in_list:
                html_parts.append(Markup('</ul>'))
                in_list = False
            level = len(header_match.group(1))
            size = {1: 20, 2: 17, 3: 15, 4: 14}.get(level, 14)
            html_parts.append(
                Markup('<div style="font-size:%spx;font-weight:bold;margin:16px 0 6px;color:%s">%s</div>')
                % (size, PRIMARY, inline(header_match.group(2)))
            )
            continue
        list_match = re.match(r'^[-*]\s+(.*)$', stripped)
        if list_match:
            flush_paragraph()
            if not in_list:
                html_parts.append(Markup('<ul style="margin:4px 0 10px;padding-left:20px">'))
                in_list = True
            html_parts.append(
                Markup('<li style="font-size:13px;line-height:1.5;color:%s">%s</li>') % (INK, inline(list_match.group(1)))
            )
            continue
        if in_list:
            html_parts.append(Markup('</ul>'))
            in_list = False
        paragraph.append(inline(stripped))
    flush_paragraph()
    if in_list:
        html_parts.append(Markup('</ul>'))
    return Markup('').join(html_parts)


def render(env, run) -> Markup:
    """Wrap the rendered body in the report's letterhead."""
    company = env.company
    base = (env['ir.config_parameter'].sudo().get_param('web.base.url', default='') or '').rstrip('/')
    link = Markup('<p style="margin:20px 0 0"><a href="%s" style="background:%s;color:#fff;padding:9px 16px;'
                  'border-radius:8px;text-decoration:none;font-size:13px">%s</a></p>') % (
        f'{base}/odoo', PRIMARY,
        env._('Open the report'),
    ) if base else Markup('')
    return Markup(
        '<div style="font-family:Arial,Helvetica,sans-serif;max-width:720px;margin:0 auto;color:%s">'
        '<div style="font-size:12px;color:%s;text-transform:uppercase;letter-spacing:.06em">%s</div>'
        '<h1 style="font-size:21px;margin:4px 0 2px;color:%s">%s</h1>'
        '<div style="font-size:12px;color:%s">%s</div>'
        '<div style="margin-top:14px;border-top:1px solid %s;padding-top:12px">%s</div>%s'
        '<p style="margin:24px 0 0;font-size:11px;color:%s">%s</p></div>'
    ) % (
        INK, MUTED, company.name, INK, run.name, MUTED, run.create_date, LINE,
        markdown_to_html(run.body_text or ''), link, MUTED,
        env._('Generated by %(agent)s on %(date)s.', agent=run.agent_id.name, date=run.create_date),
    )


def run_agent(schedule) -> tuple[str, str | None]:
    """Run the schedule's agent synchronously and return ``(text, error)``.

    Uses the same session engine as an interactive chat, but drains it in
    this transaction with ``_run_to_completion`` instead of handing it to
    the async worker, since the cron needs the final answer now to render
    and send it.
    """
    env = schedule.env
    Session = env['aypatech_wooai.session'].sudo()
    session = Session.create({
        'name': schedule.name,
        'agent_id': schedule.agent_id.id,
    })
    try:
        session.start(schedule.prompt or env._('Produce the report.'))
        session._run_to_completion()
    except Exception as error:  # noqa: BLE001 — the run must record the failure, not raise
        _logger.exception('report schedule %s: agent run failed', schedule.id)
        return '', str(error)[:2000]
    if session.state == 'error':
        return '', (session.last_text or env._('The agent run failed.'))[:2000]
    return session.last_text or '', None


def attach_pdf(run) -> None:
    """Render the run to PDF and attach it, recording a soft failure otherwise."""
    env = run.env
    try:
        pdf, _kind = env['ir.actions.report'].sudo().with_context(lang=run.lang)._render_qweb_pdf(PDF_REPORT, run.ids)
    except Exception as error:  # noqa: BLE001 — PDF rendering may legitimately be unavailable
        _logger.warning('report run %s: no PDF (%s)', run.id, error)
        run.pdf_error = env._(
            'No PDF: the server has no PDF engine (wkhtmltopdf). The report is still sent as e-mail.'
        )
        return
    attachment = env['ir.attachment'].sudo().create({
        'name': '%s.pdf' % run.name.replace('/', '-'),
        'raw': pdf,
        'mimetype': 'application/pdf',
        'res_model': run._name,
        'res_id': run.id,
    })
    run.pdf_id = attachment


def send_email(run, emails: list[str]) -> bool:
    """E-mail the run's rendered body, with the PDF attached when available."""
    env = run.env
    emails = [e for e in emails if e]
    if not emails:
        return False
    company = run.company_id
    mail = env['mail.mail'].sudo().create({
        'subject': run.name,
        'body_html': run.body_html,
        'email_to': ', '.join(emails),
        'email_from': company.email_formatted or env.user.email_formatted or company.partner_id.email_formatted,
        'attachment_ids': [(4, run.pdf_id.id)] if run.pdf_id else [],
        'auto_delete': False,
    })
    mail.send()
    if mail.state == 'exception':
        run.write({
            'error': env._(
                'The report was made, but the e-mail could not be sent: %(reason)s',
                reason=mail.failure_reason or env._('no outgoing mail server'),
            ),
        })
        return False
    run.write({'sent_to': '\n'.join(filter(None, [run.sent_to] + emails))})
    return True


def send_telegram(run, bot_token: str, chat_ids: list[str]) -> list[str]:
    """Send the run by Telegram Bot API, returning the chat ids that succeeded."""
    chat_ids = [c.strip() for c in chat_ids if c and c.strip()]
    if not bot_token or not chat_ids:
        return []
    ok_chats = []
    caption = run.name[:1020]
    for chat_id in chat_ids:
        try:
            if run.pdf_id:
                response = requests.post(
                    f'{TELEGRAM_BASE_URL}/bot{bot_token}/sendDocument',
                    data={'chat_id': chat_id, 'caption': caption},
                    files={'document': (f'{run.name}.pdf', run.pdf_id.raw, 'application/pdf')},
                    timeout=30,
                )
            else:
                text = re.sub('<[^<]+?>', '', run.body_text or '')[:TELEGRAM_MESSAGE_LIMIT]
                response = requests.post(
                    f'{TELEGRAM_BASE_URL}/bot{bot_token}/sendMessage',
                    data={'chat_id': chat_id, 'text': text},
                    timeout=30,
                )
            response.raise_for_status()
            if response.json().get('ok'):
                ok_chats.append(chat_id)
        except requests.RequestException:
            _logger.exception('report run %s: telegram send to %s failed', run.id, chat_id)
    return ok_chats


def make_run(schedule):
    """Run the agent, render the result, attach a PDF, and create the run record."""
    env = schedule.env
    text, error = run_agent(schedule)
    Run = env['aypatech_wooai.report.run'].sudo()
    run = Run.create({
        'name': schedule.name,
        'schedule_id': schedule.id,
        'agent_id': schedule.agent_id.id,
        'company_id': schedule.company_id.id,
        'lang': env.lang,
        'body_text': text,
        'state': 'failed' if error else 'done',
        'error': error,
    })
    if not error:
        run.body_html = render(env, run)
        attach_pdf(run)
    return run


def send_schedule(schedule):
    """Build one run per recipient language and deliver it by e-mail and Telegram."""
    by_lang = {}
    for _user, email, lang in schedule.recipients():
        by_lang.setdefault(lang or 'en_US', []).append(email)
    if not by_lang:
        by_lang[schedule.lang or 'en_US'] = []
    runs = schedule.env['aypatech_wooai.report.run'].sudo()
    telegram_chat_ids = [c.strip() for c in (schedule.telegram_chat_ids or '').split(',') if c.strip()]
    for lang, emails in by_lang.items():
        env = schedule.with_context(lang=lang).with_company(schedule.company_id).env
        run = make_run(schedule.with_env(env))
        if run.state != 'failed':
            if emails:
                send_email(run, emails)
            if schedule.telegram_enabled and telegram_chat_ids:
                sent = send_telegram(run, schedule.sudo().telegram_bot_token, telegram_chat_ids)
                if sent:
                    run.write({'telegram_sent_to': ', '.join(sent)})
            run.write({'state': 'sent', 'sent_at': run.create_date})
        runs |= run
    return runs
