# -*- coding: utf-8 -*-
"""
Al Ahram Cookware — Discuss Channel AI Auto-Responder
=====================================================
Integrates Odoo Discuss channels with Al Ahram Chatbot Service.
When a user posts a message to an AI Chat channel (or mentions AlAhram bot),
the bot automatically queries the live database and posts the answer back.
"""

import logging
from markupsafe import Markup
from odoo import models, api, tools

_logger = logging.getLogger(__name__)


class DiscussChannelAI(models.Model):
    _inherit = 'discuss.channel'

    def message_post(self, **kwargs):
        """Overrides message_post to generate live AI chatbot answers in AI channels."""
        message = super().message_post(**kwargs)

        # Prevent recursion if message is generated by our AI
        if self.env.context.get('alahram_ai_auto_reply'):
            return message

        for channel in self:
            # Check if this channel is an AI chat or has an AI agent attached
            ai_agent = getattr(channel.sudo(), 'ai_agent_id', False)
            channel_type = getattr(channel, 'channel_type', None)
            is_ai_channel = (channel_type == 'ai_chat') or bool(ai_agent)
            if not is_ai_channel:
                continue

            # Identify Bot partner ID
            odoobot = self.env.ref('base.partner_root', raise_if_not_found=False)
            bot_partner_id = ai_agent.partner_id.id if (ai_agent and getattr(ai_agent, 'partner_id', False)) else (odoobot.id if odoobot else 1)

            # Only reply if message is from a real user (not from the AI bot)
            if message.author_id.id == bot_partner_id:
                continue

            raw_body = kwargs.get('body') or message.body or ''
            clean_text = tools.html2plaintext(raw_body).strip()
            if not clean_text:
                continue

            try:
                # Ask Al Ahram AI Service with live DB context
                ai_result = self.env['alahram.chatbot.service'].sudo().ask_ai(
                    question=clean_text,
                    channel='discuss',
                    user_id=message.author_id.user_ids[:1].id if message.author_id.user_ids else self.env.user.id
                )

                if ai_result and ai_result.get('html'):
                    channel.sudo().with_context(alahram_ai_auto_reply=True).message_post(
                        body=Markup(ai_result['html']),
                        author_id=bot_partner_id,
                        message_type='comment',
                        subtype_xmlid='mail.mt_comment',
                    )
            except Exception as e:
                _logger.exception("Error generating Al Ahram AI Discuss auto-reply: %s", str(e))

        return message
